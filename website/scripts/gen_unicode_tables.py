"""Generate src/lib/unicodeTables.ts: the exact code-point sets scikit-learn relies on.
  WORD      = characters matched by Python's re `\\w` (str patterns, Unicode)  -> token_pattern (?u)\\b\\w\\w+\\b
  COMBINING = unicodedata.combining(c) != 0                                     -> strip_accents='unicode'
Run from website/:  python scripts/gen_unicode_tables.py"""
import json, os, re, sys, unicodedata
w = re.compile(r"\w")
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None: start = cp
        if not ok and start is not None: out.append([start, cp - 1]); start = None
    if start is not None: out.append([start, 0x10FFFF])
    return out
word = ranges(lambda cp: not (0xD800 <= cp <= 0xDFFF) and bool(w.match(chr(cp))))
comb = ranges(lambda cp: unicodedata.combining(chr(cp)) != 0)
WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(WEB, "src", "lib", "unicodeTables.ts"), "w") as f:
    f.write(f"// AUTO-GENERATED by scripts/gen_unicode_tables.py from Python {sys.version.split()[0]} "
            f"(Unicode {unicodedata.unidata_version}). Do not edit by hand.\n"
            f"export const UNICODE_VERSION = {json.dumps(unicodedata.unidata_version)};\n"
            f"export const WORD_RANGES: [number, number][] = {json.dumps(word, separators=(',', ':'))};\n"
            f"export const COMBINING_RANGES: [number, number][] = {json.dumps(comb, separators=(',', ':'))};\n")
print(len(word), "word ranges,", len(comb), "combining ranges")
